RESUME_KEYS = {("t",), ("ts", "seq"), ("ts", "seq", "side", "price")}
# Time inputs: the contract's RFC 3339 string, date or epoch milliseconds; the client also takes datetime and
# date objects and writes them out (``_http.format_time``).
TIMESTAMP_INPUT = "TimestampInput"
TIMESTAMP_INPUT_TYPE = "str | int | datetime | date"
STREAM_FORMATS = {"application/x-ndjson": "ndjson", "text/csv": "csv"}
HEADER = (
    "# Generated by scripts/generate.py from the Qelso API contract {version} "
    "(openapi.v2.yaml sha256 {sha}).\n# Don't edit: change the contract, then run the script.\n"
)


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[_\-]", name) if part)


def py_name(wire: str) -> str:
    name = re.sub(r"\W", "_", wire)
    return name + "_" if keyword.iskeyword(name) or name in {"from", "async"} else name


def literal(values: list[Any]) -> str:
    return "Literal[" + ", ".join(json.dumps(v) for v in values) + "]"


def doc_lines(text: str | None) -> list[str]:
    """A description as docstring lines: markdown kept, quotes and backslashes made safe."""
    if not text:
        return []
    text = text.strip().replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return [line.rstrip() for line in text.splitlines()]


def docstring(text: str | None, indent: str, extra: list[str] | None = None) -> list[str]:
    lines = doc_lines(text) + (extra or [])
    if not lines:
        return []
    if len(lines) == 1 and not lines[0].endswith('"'):
        return [f'{indent}"""{lines[0]}"""']
    body = [f"{indent}{line}" if line else "" for line in lines]
    return [f'{indent}"""{body[0].lstrip()}', *body[1:], f'{indent}"""']


@dataclass
class FieldDef:
    name: str
    wire: str
    annotation: str
    optional: bool
    doc: str | None


@dataclass
class ModelDef:
    name: str
    doc: str | None
    base: str
    fields: list[FieldDef] = field(default_factory=list)


@dataclass
class Param:
    wire: str
    name: str
    location: str  # path, query or body
    required: bool
    annotation: str
    encoding: str  # path, scalar, time, date, repeat, csv, model
    doc: str | None


@dataclass
class Operation:
    operation_id: str
    method: str
    path: str
    summary: str
    description: str | None
    params: list[Param]
    response: str
    accept_statuses: list[int]
    row: str | None  # the row model when the operation pages
    stream_formats: list[str]
    resume_key: tuple[str, ...] | None


class Contract:
    def __init__(self, doc: dict[str, Any]) -> None:
        self.doc = doc
        self.schemas: dict[str, Any] = doc["components"]["schemas"]
        self.parameters: dict[str, Any] = doc["components"]["parameters"]
        self.models: list[ModelDef] = []
        self.aliases: list[tuple[str, str, str | None]] = []
        self.closed_enums: set[str] = set()
        self.response_models: set[str] = set()
        for path_item in doc["paths"].values():
            for op in path_item.values():
                for status, response in op["responses"].items():
                    schema = response.get("content", {}).get("application/json", {}).get("schema", {})
                    if (status.startswith("2") or status == "503") and "$ref" in schema:
                        name = self.ref_name(schema)
                        if name != "Error":
                            self.response_models.add(name)

    # ---------- schemas ----------
    @staticmethod
    def ref_name(schema: dict[str, Any]) -> str:
        return str(schema["$ref"]).rsplit("/", 1)[-1]

    def resolve(self, schema: dict[str, Any]) -> dict[str, Any]:
        while "$ref" in schema:
            schema = self.schemas[self.ref_name(schema)]
        return schema

    def nullable(self, schema: dict[str, Any]) -> bool:
        if "$ref" in schema:
            return self.nullable(self.schemas[self.ref_name(schema)])
        if "anyOf" in schema:
            return any(self.nullable(option) for option in schema["anyOf"])
        kind = schema.get("type")
        return kind == "null" or (isinstance(kind, list) and "null" in kind) or None in schema.get("enum", [])

    @staticmethod
    def is_model(schema: dict[str, Any]) -> bool:
        return schema.get("type") == "object" and "properties" in schema

    def is_closed_enum(self, schema: dict[str, Any]) -> bool:
        return "enum" in schema and "anyOf" not in schema

    def response_type(self, schema: dict[str, Any], owner: str, field_name: str) -> str:
        """The type a response field is read as (lenient: every enum also takes other strings)."""
        if "$ref" in schema:
            name = self.ref_name(schema)
            return f"{name} | str" if name in self.closed_enums else name
        if "anyOf" in schema:
            options = [o for o in schema["anyOf"] if o.get("type") != "null"]
            types: list[str] = []
            for option in options:
                for part in self.response_type(option, owner, field_name).split(" | "):
                    if part not in types:
                        types.append(part)
            if "str" in types:  # an open enum, or a closed one read leniently
                types = [t for t in types if t != "str"] + ["str"]
            if len(options) < len(schema["anyOf"]):
                types.append("None")
            return " | ".join(types)
        kind = schema.get("type")
        if isinstance(kind, list):
            base = [k for k in kind if k != "null"]
            inner = dict(schema, type=base[0] if len(base) == 1 else base)
            if "enum" in schema:
                inner["enum"] = [v for v in schema["enum"] if v is not None]
            text = self.response_type(inner, owner, field_name)
            return f"{text} | None" if "null" in kind else text
        if "enum" in schema:
            return f"{literal(schema['enum'])} | str"
        if kind == "string":
            return {"date-time": "datetime", "date": "date"}.get(schema.get("format", ""), "str")
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            if "prefixItems" in schema:
                return "tuple[" + ", ".join(self.alias_text(item) for item in schema["prefixItems"]) + "]"
            return f"list[{self.response_type(schema['items'], owner, field_name)}]"
        if kind == "object":
            if "properties" in schema:
                return self.inline_model(schema, owner, field_name)
            return "dict[str, Any]"
        return "Any"

    def alias_text(self, schema: dict[str, Any], name: str = "") -> str:
        """An alias's definition: strict for closed enums (they type parameters too)."""
        if name == TIMESTAMP_INPUT:
            kinds = sorted(o.get("format", o.get("type")) for o in schema.get("anyOf", []))
            if kinds != ["date", "date-time", "integer"]:
                raise SystemExit(f"TimestampInput changed ({kinds}): update TIMESTAMP_INPUT_TYPE")
            return TIMESTAMP_INPUT_TYPE
        if "$ref" in schema:
            return self.ref_name(schema)
        if self.is_closed_enum(schema) and schema.get("type") == "string":
            return literal(schema["enum"])
        return self.response_type(schema, "", "")

    def inline_model(self, schema: dict[str, Any], owner: str, field_name: str) -> str:
        name = INLINE_NAMES.get((owner, field_name)) or owner + pascal(field_name)
        if not any(model.name == name for model in self.models):
            self.add_model(name, schema, base="QelsoModel")
        return name

    def add_model(self, name: str, schema: dict[str, Any], base: str) -> None:
        model = ModelDef(name=name, doc=schema.get("description"), base=base)
        required = set(schema.get("required", []))
        fields = []
        for wire, prop in schema["properties"].items():
            annotation = self.response_type(prop, name, wire)
            optional = wire not in required or self.nullable(prop)
            if optional and "None" not in annotation.split(" | "):
                annotation += " | None"
            fields.append(FieldDef(py_name(wire), wire, annotation, optional, prop.get("description")))
        model.fields = fields
        self.models.append(model)  # after its inline models, which add_model added on the way

    def build_models(self) -> None:
        for name, schema in self.schemas.items():
            if not self.is_model(schema) and self.is_closed_enum(schema) and schema.get("type") == "string":
                self.closed_enums.add(name)
        for name, schema in self.schemas.items():
            if self.is_model(schema):
                base = "QelsoResponse" if name in self.response_models else "QelsoModel"
                self.add_model(name, schema, base)
            else:
                self.aliases.append((name, self.alias_text(schema, name), schema.get("description")))

    # ---------- parameters and operations ----------
    def param_type(self, schema: dict[str, Any]) -> tuple[str, str]:
        """A parameter's (annotation, encoding)."""
        if "$ref" in schema:
            name = self.ref_name(schema)
            return name, "time" if name == "TimestampInput" else "scalar"
        if "anyOf" in schema:
            parts = [self.param_type(option)[0] for option in schema["anyOf"]]
            return " | ".join(parts), "scalar"
        kind = schema.get("type")
        if kind == "array":
            item, _ = self.param_type(schema["items"])
            return item, "array"
        if "enum" in schema:
            return literal(schema["enum"]), "scalar"
        if kind == "string" and schema.get("format") == "date":
            return "str | date", "date"
        return {"integer": "int", "number": "float", "boolean": "bool"}.get(kind or "", "str"), "scalar"

    def param(self, spec: dict[str, Any]) -> Param:
        override = {k: v for k, v in spec.items() if k != "$ref"}
        if "$ref" in spec:
            spec = {**self.parameters[self.ref_name(spec)], **override}
        style = spec.get("style", "form" if spec["in"] == "query" else "simple")
        if spec["in"] not in ("path", "query") or style not in ("form", "simple"):
            raise SystemExit(f"parameter {spec['name']}: {spec['in']}/{style} isn't sent by the SDK yet")
        annotation, encoding = self.param_type(spec["schema"])
        if encoding == "array":
            encoding = "repeat" if spec.get("explode", True) else "csv"
            annotation = f"{annotation} | Sequence[{annotation}]"
        if spec["in"] == "path":
            encoding = "path"
        return Param(
            wire=spec["name"],
            name=py_name(spec["name"]),
            location=spec["in"],
            required=bool(spec.get("required")),
            annotation=annotation,
            encoding=encoding,
            doc=spec.get("description"),
        )

    def body_params(self, op: dict[str, Any]) -> list[Param]:
        if "requestBody" not in op:
            return []
        schema = op["requestBody"]["content"]["application/json"]["schema"]
        name = self.ref_name(schema)
        body = self.schemas[name]
        params = []
        for wire, prop in body["properties"].items():
            if "$ref" in prop:
                annotation, encoding = self.param_type(prop)
            elif self.is_model(prop):
                annotation = f"{INLINE_NAMES.get((name, wire)) or name + pascal(wire)} | Mapping[str, Any]"
                encoding = "model"
            else:
                annotation, encoding = self.param_type(prop)
            params.append(
                Param(
                    wire,
                    py_name(wire),
                    "body",
                    wire in body.get("required", []),
                    annotation,
                    encoding,
                    prop.get("description"),
                )
            )
        return params

    def operations(self) -> list[Operation]:
        ops = []
        for path, path_item in self.doc["paths"].items():
            for method, op in path_item.items():
                params = [self.param(p) for p in op.get("parameters", [])] + self.body_params(op)
                success = {s: r for s, r in op["responses"].items() if s.startswith("2")}
                response = next(iter(success.values()))
                content = response["content"]
                model = self.ref_name(content["application/json"]["schema"])
                accept = [
                    int(s)
                    for s, r in op["responses"].items()
                    if not s.startswith("2")
                    and r.get("content", {})
                    .get("application/json", {})
                    .get("schema", {})
                    .get("$ref", "")
                    .endswith("/" + model)
                ]
                page = self.schemas[model]
                row = None
                if "next_cursor" in page.get("properties", {}):
                    row = self.ref_name(page["properties"]["data"]["items"])
                formats = [STREAM_FORMATS[ct] for ct in content if ct in STREAM_FORMATS]
                resume = None
                if formats:
                    resume = self.resume_key(op, [p for p in params if p.wire == "after"])
                ops.append(
                    Operation(
                        operation_id=op["operationId"],
                        method=method.upper(),
                        path=path,
                        summary=op.get("summary", ""),
                        description=op.get("description"),
                        params=params,
                        response=model,
                        accept_statuses=accept,
                        row=row,
                        stream_formats=formats,
                        resume_key=resume,
                    )
                )
        return ops

    def resume_key(self, op: dict[str, Any], after: list[Param]) -> tuple[str, ...]:
        if not after:
            raise SystemExit(f"{op['operationId']} streams but has no `after` parameter")
        refs = [p for p in op["parameters"] if p.get("name") == "after" or "$ref" in p]
        if any(p.get("$ref", "").endswith("/AfterT") for p in refs):
            key: tuple[str, ...] = ("t",)
        else:
            found = re.search(r"Format `<([^`]+)>`", after[0].doc or "")
            if not found:
                raise SystemExit(f"{op['operationId']}: can't read the resume key from `after`")
            key = tuple(part.strip("<>") for part in found.group(1).split(","))
        if key not in RESUME_KEYS:
            raise SystemExit(f"{op['operationId']}: unknown resume key {key}; teach the stream reader first")
        return key


# ---------- rendering ----------
def render_models(contract: Contract, header: str) -> str:
    info = contract.doc["info"]
    out = [
        header,
        f'"""Models for every object in the Qelso Data API contract ({info["version"]}).',
        "",
        "Each is a pydantic model with the contract's field names. Responses are read leniently: fields the",
        "contract adds later are kept (``model_extra``), every enum also accepts other strings, and nullable",
        'or optional fields default to None."""',
        "",
        "from __future__ import annotations",
        "",
        "@IMPORTS@",
        "",
        "from qelso._model import QelsoModel, QelsoResponse",
        "",
        f"API_VERSION = {json.dumps(info['version'])}",
        '"""The contract version these models follow."""',
        "",
    ]
    for name, text, doc in contract.aliases:
        out.append(f"{name} = {text}")  # evaluated at import: ``X | Y`` of typing forms needs Python 3.10
        out.extend(docstring(doc, ""))
        out.append("")
    for model in contract.models:
        out.append("")
        out.append(f"class {model.name}({model.base}):")
        body = docstring(model.doc, "    ")
        for f in model.fields:
            if f.name != f.wire:
                raise SystemExit(
                    f"{model.name}.{f.wire}: a field name that isn't a Python name needs an alias"
                )
            default = " = None" if f.optional else ""
            body.append(f"    {f.name}: {f.annotation}{default}")
            body.extend(docstring(f.doc, "    "))
        out.extend(body or ["    pass"])
        out.append("")
    out.append("")
    names = [n for n, _, _ in contract.aliases] + [m.name for m in contract.models]
    out.append("__all__ = [" + ", ".join(json.dumps(n) for n in ["API_VERSION", *names]) + "]")
    text = "\n".join(out) + "\n"
    return text.replace(
        "@IMPORTS@", imports(text, {"datetime": ["date", "datetime"], "typing": ["Any", "Literal"]})
    )


def imports(text: str, wanted: dict[str, list[str]]) -> str:
    """Import lines for the names the generated code uses (names in code, not words in docstrings)."""
    names_used = {
        node.id for node in ast.walk(ast.parse(text.replace("@IMPORTS@", ""))) if isinstance(node, ast.Name)
    }
    lines = []
    for module, names in wanted.items():
        used = [n for n in names if n in names_used]
        if used:
            lines.append(f"from {module} import {', '.join(used)}")
    return "\n".join(lines)


def signature(params: list[Param], extra: list[str], positional: list[Param]) -> list[str]:
    lines = ["        self,"]
    lines += [f"        {p.name}: {p.annotation}," for p in positional]
    keyword_only = [p for p in params if p not in positional]
    if keyword_only or extra:
        lines.append("        *,")
    lines += [f"        {p.name}: {p.annotation}," for p in keyword_only if p.required]
    lines += [f"        {p.name}: {p.annotation} | None = None," for p in keyword_only if not p.required]
    lines += [f"        {e}," for e in extra]
    return lines


# For the few parameters the contract leaves undescribed (path IDs and some query filters).
PARAM_DOCS = {
    "venue": "A venue code: `kalshi` or `polymarket`.",
    "start": "Start of the range, inclusive.",
    "end": "End of the range, exclusive.",
}


def args_doc(params: list[Param], extra: dict[str, str] | None = None) -> list[str]:
    lines = []
    for p in params:
        text = " ".join(doc_lines(p.doc)) or PARAM_DOCS.get(p.name, "")
        lines.append(f"    {p.name}: {text}")
    for name, text in (extra or {}).items():
        lines.append(f"    {name}: {text}")
    return ["", "Args:", *lines] if lines else []


def call_args(op: Operation, params: list[Param]) -> list[str]:
    path = [p for p in params if p.location == "path"]
    query = [p for p in params if p.location == "query"]
    body = [p for p in params if p.location == "body"]
    lines = [f"            {json.dumps(op.path)},"]
    lines.append("            path={" + ", ".join(f"{json.dumps(p.wire)}: {p.name}" for p in path) + "},")
    if query:
        lines.append("            query=(")
        lines += [
            f"                ({json.dumps(p.wire)}, {p.name}, {json.dumps(p.encoding)})," for p in query
        ]
        lines.append("            ),")
    if body:
        lines.append("            body=(")
        lines += [
            f"                ({json.dumps(p.wire)}, {p.name}, {json.dumps(p.encoding)})," for p in body
        ]
        lines.append("            ),")
    return lines


def render_operation(op: Operation, asynchronous: bool) -> list[str]:
    name = snake(op.operation_id)
    stem = re.sub(r"^(get|list)_", "", name)
    positional = [p for p in op.params if p.location == "path"]
    out: list[str] = []

    # One page (or the object).
    page_params = [p for p in op.params if p.wire != "after"]
    defn = "async def" if asynchronous else "def"
    out.append(f"    {defn} {name}(")
    out += signature(page_params, [], positional)
    out.append(f"    ) -> {op.response}:")
    summary = op.summary + ("." if not op.summary.endswith(".") else "")
    text = summary + ("\n\n" + op.description if op.description else "")
    out += docstring(text, "        ", args_doc(page_params))
    awaited = "await " if asynchronous else ""
    out.append(f"        return {awaited}self._request_model(")
    out.append(f"            {json.dumps(op.method)},")
    out += call_args(op, page_params)
    out.append(f"            model={op.response},")
    if op.accept_statuses:
        out.append(f"            accept={tuple(op.accept_statuses)!r},")
    out.append("        )")
    out.append("")

    pager = "AsyncPager" if asynchronous else "SyncPager"
    stream = "AsyncStream" if asynchronous else "SyncStream"
    if op.row:
        params = [p for p in op.params if p.wire != "after"]
        out.append(f"    def iter_{stem}(")
        out += signature(params, [], positional)
        out.append(f"    ) -> {pager}[{op.row}]:")
        loop = "async for" if asynchronous else "for"
        text = (
            f"Every {op.row} of {name}, page after page (``{loop} row in ...``).\n\n"
            f"Follows ``next_cursor`` until the last page; ``.pages()`` gives the pages instead, and "
            f"``.to_pandas()`` a DataFrame. Each page costs what one {name} call costs. To carry on a run "
            f"that stopped, pass the pager's ``next_cursor`` as ``cursor`` (valid 24 hours)."
        )
        out += docstring(text, "        ", args_doc(params))
        out.append("        return self._paginate(")
        out.append(f"            {json.dumps(op.method)},")
        out += call_args(op, [p for p in params if p.wire != "cursor"])
        out.append(f"            model={op.response},")
        out.append("            cursor=cursor,")
        out.append("        )")
        out.append("")

    if op.stream_formats:
        params = [p for p in op.params if p.wire not in ("after", "cursor", "limit")]
        if any(p.name in ("format", "max_resumes") for p in params):
            raise SystemExit(f"{op.operation_id}: a parameter clashes with the stream's own arguments")
        after = next(p for p in op.params if p.wire == "after")
        formats = op.stream_formats
        extra = [
            f"after: {after.annotation} | None = None",
            f"format: {literal(formats)} = {json.dumps(formats[0])}",
            "max_resumes: int = 10",
        ]
        out.append(f"    def stream_{stem}(")
        out += signature(params, extra, positional)
        out.append(f"    ) -> {stream}[{op.row}]:")
        key = ",".join(f"<{k}>" for k in op.resume_key or ())
        text = (
            f"Stream every {op.row} in the window as {' or '.join(f.upper() for f in formats)}: one request, "
            f"however many rows.\n\n"
            f"If the connection breaks, the stream resumes by itself after the last row received "
            f"(``after={key}``), so no row is repeated or skipped; once rows flow, it waits out an outage. "
            f"Before the first row, the client's ``max_retries`` applies and the API's own error is raised. "
            f"It costs what one page costs; tick rows count against your monthly quota. ``.to_pandas()`` "
            f"reads it into a DataFrame and ``.save(path)`` writes it to a file."
        )
        extra_doc = {
            "after": " ".join(doc_lines(after.doc)),
            "format": "`ndjson` (rows as models) or `csv` (the fastest way into pandas or a file)."
            if len(formats) > 1
            else "Only `ndjson`: books stream as NDJSON.",
            "max_resumes": "Once rows flow, failures in a row (breaks or failed requests, no new row "
            "between them) before APIConnectionError is raised; a new row resets the count.",
        }
        out += docstring(text, "        ", args_doc(params, extra_doc))
        out.append("        return self._stream(")
        out += call_args(op, params)
        out.append(f"            row={op.row},")
        out.append(f"            key={tuple(op.resume_key or ())!r},")
        out.append(f"            formats={tuple(formats)!r},")
        out.append("            format=format,")
        out.append("            after=after,")
        out.append("            max_resumes=max_resumes,")
        out.append("        )")
        out.append("")
    return out


def render_operations(contract: Contract, ops: list[Operation], header: str) -> str:
    version = contract.doc["info"]["version"]
    used = sorted(
        {op.response for op in ops}
        | {op.row for op in ops if op.row}
        | {
            word
            for op in ops
            for p in op.params
            for word in re.findall(r"\b[A-Z][A-Za-z]+\b", p.annotation)
            if word not in ("Literal", "Sequence", "Mapping", "Any")
        }
    )
    out = [
        header,
        f'"""Every operation of the Qelso Data API contract ({version}), sync and async."""',
        "",
        "from __future__ import annotations",
        "",
        "@IMPORTS@",
        "",
        "from qelso._base import AsyncBase, SyncBase",
        "from qelso._paging import AsyncPager, SyncPager",
        "from qelso._streams import AsyncStream, SyncStream",
        "from qelso.models import (",
        *[f"    {name}," for name in used],
        ")",
        "",
        '__all__ = ["AsyncOperations", "SyncOperations"]',
        "",
        "",
        "class SyncOperations(SyncBase):",
        '    """The operations, one method each."""',
        "",
    ]
    for op in ops:
        out += render_operation(op, asynchronous=False)
    out += [
        "",
        "class AsyncOperations(AsyncBase):",
        '    """The operations as coroutines; ``iter_*`` and ``stream_*`` return async iterables."""',
        "",
    ]
    for op in ops:
        out += render_operation(op, asynchronous=True)
    text = "\n".join(out).rstrip() + "\n"
    wanted = {
        "collections.abc": ["Mapping", "Sequence"],
        "datetime": ["date"],
        "typing": ["Any", "Literal"],
    }
    return text.replace("@IMPORTS@", imports(text, wanted))


def ruff(text: str, path: Path) -> str:
    """The generated text as the repo's ruff leaves it: imports and ``__all__`` sorted, then formatted."""
    name = str(path.relative_to(SDK))
    for command in (
        ["ruff", "check", "--fix-only", "--select", "I,RUF022", "--stdin-filename", name, "-"],
        ["ruff", "format", "--stdin-filename", name, "-"],
    ):
        result = subprocess.run(command, input=text, capture_output=True, text=True, cwd=SDK, check=False)
        if result.returncode != 0:
            raise SystemExit(f"{' '.join(command[:2])} failed on the generated {path.name}:\n{result.stderr}")
        text = result.stdout
    return text


def generate() -> dict[Path, str]:
    doc = json.loads(CONTRACT_JSON.read_text(encoding="utf-8"))
    sha = hashlib.sha256(CONTRACT_YAML.read_bytes()).hexdigest()
    header = HEADER.format(version=doc["info"]["version"], sha=sha)
    contract = Contract(doc)
    contract.build_models()
    ops = contract.operations()
    return {
        MODELS_PATH: ruff(render_models(contract, header), MODELS_PATH),
        OPERATIONS_PATH: ruff(render_operations(contract, ops, header), OPERATIONS_PATH),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    args = parser.parse_args()
    files = generate()
    stale = []
    for path, text in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == text:
            continue
        stale.append(path)
        if args.check:
            diff = difflib.unified_diff(
                current.splitlines(), text.splitlines(), str(path.relative_to(SDK)), "generated", lineterm=""
            )
            print("\n".join(list(diff)[:60]), file=sys.stderr)
        else:
            path.write_text(text, encoding="utf-8")
    if args.check and stale:
        names = ", ".join(str(p.relative_to(SDK)) for p in stale)
        print(f"out of date: {names}; run `uv run python scripts/generate.py`", file=sys.stderr)
        return 1
    if not args.check:
        print(f"wrote {len(stale)} file(s)" if stale else "up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
