#!/usr/bin/env python3
"""Generate the SDK's models and operations from the Qelso API contract.

    uv run python scripts/generate.py           # from sdk/: rewrite the two generated files
    uv run python scripts/generate.py --check   # CI: fail if they differ from what the contract gives

The contract is ``api/qelso_api/contract/openapi.v2.json``, the served copy of ``openapi.v2.yaml`` (its source
of truth; api/'s CI checks the JSON is the YAML rebuilt). The public SDK repo carries both in ``contract/``
(``scripts/sync_public.py``). Two files come out of it:

- ``src/qelso/models.py``: one pydantic model per object schema, one type alias per other schema.
- ``src/qelso/_operations.py``: one method per operation, on a sync and an async class, plus ``iter_*``
  (every page, following ``next_cursor``) for each operation that pages and ``stream_*`` (NDJSON or CSV,
  resumed with ``after=`` when the connection breaks) for each operation that streams.

Responses are read leniently, so a customer's code never breaks on data the contract allows or on a later
addition within v2 (contract notes §6): unknown fields are kept, every enum also accepts other strings, and
the contract's ranges and patterns aren't enforced on responses. Nullable fields default to None.
Parameters are typed strictly (closed enums as ``Literal``); the API checks their values.
"""

